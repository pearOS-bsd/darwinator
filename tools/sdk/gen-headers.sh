#!/bin/sh
# the two headers of xnu's bsd/sys that its make_*.sh generate from the SDK of Xcode, made here without it:  sh gen-headers.sh OUTDIR  ->  OUTDIR/sys/_symbol_aliasing.h, OUTDIR/sys/_posix_availability.h
# (same content as xnu's scripts: for each macOS version a macro that is its argument when the deployment target is at least that version; for each POSIX level a deprecation macro)
set -e
O="${1:-inc}"; mkdir -p "$O/sys"
{
echo '/* generated by tools/sdk/gen-headers.sh (the format of xnu bsd/sys/make_symbol_aliasing.sh) */'
echo '#ifndef _CDEFS_H_'; echo '# error "Never use <sys/_symbol_aliasing.h> directly.  Use <sys/cdefs.h> instead."'; echo '#endif'; echo
for v in 10.0 10.1 10.2 10.3 10.4 10.5 10.6 10.7 10.8 10.9 10.10 10.11 10.12 10.13 10.14 10.15 10.16 \
         11.0 11.1 11.2 11.3 11.4 11.5 11.6 11.7 12.0 12.1 12.2 12.3 12.4 12.5 12.6 12.7 13.0 13.1 13.2 13.3 13.4 13.5 13.6 13.7 \
         14.0 14.1 14.2 14.3 14.4 14.5 14.6 14.7 14.8 15.0 15.1 15.2 15.3 15.4 15.5 15.6 15.7 26.0 26.1 26.2 26.3 26.4; do
	maj=${v%%.*}; min=${v#*.}
	if [ "$maj" -eq 10 ] && [ "$min" -lt 10 ]; then value=$(printf "%d%d0" "$maj" "$min"); else value=$(printf "%d%02d00" "$maj" "$min"); fi
	str="__MAC_${maj}_${min}"
	echo "#if defined(__ENVIRONMENT_MAC_OS_X_VERSION_MIN_REQUIRED__) && __ENVIRONMENT_MAC_OS_X_VERSION_MIN_REQUIRED__ >= ${value}"
	echo "#define __DARWIN_ALIAS_STARTING_MAC_${str}(x) x"
	echo "#else"
	echo "#define __DARWIN_ALIAS_STARTING_MAC_${str}(x)"
	echo "#endif"; echo
done
} > "$O/sys/_symbol_aliasing.h"
{
echo '/* generated by tools/sdk/gen-headers.sh (the format of xnu bsd/sys/make_posix_availability.sh) */'
echo '#ifndef _CDEFS_H_'; echo '# error "Never use <sys/_posix_availability.h> directly.  Use <sys/cdefs.h> instead."'; echo '#endif'; echo
for value in 198808L 199009L 199209L 199309L 199506L 200112L 200809L; do
	echo "#if !defined(_DARWIN_C_SOURCE) && defined(_POSIX_C_SOURCE) && _POSIX_C_SOURCE >= ${value}"
	echo "#define ___POSIX_C_DEPRECATED_STARTING_${value} __deprecated"
	echo "#else"; echo "#define ___POSIX_C_DEPRECATED_STARTING_${value}"; echo "#endif"; echo
done
} > "$O/sys/_posix_availability.h"
echo "made $O/sys/_symbol_aliasing.h and $O/sys/_posix_availability.h"
